package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// hookPattern 匹配 .def 文件里定义的 Hook 条目。
var hookPattern = regexp.MustCompile(`^([A-Z0-9_]+)\s*\(\s*([A-Za-z0-9_]+)\s*,`)

// main 解析 CLI 参数并触发头文件生成。
func main() {
	var (
		defPath   string
		output    string
		extraPath string
	)
	flag.StringVar(&defPath, "def", "", "path to the .def file that enumerates hook templates")
	flag.StringVar(&output, "o", "", "path to the generated header file")
	flag.StringVar(&extraPath, "extra", "", "optional file with additional hook symbols (one per line)")
	flag.Parse()

	if defPath == "" || output == "" {
		flag.Usage()
		os.Exit(2)
	}

	hooks, err := readHookTargets(defPath)
	if err != nil {
		fatal(err)
	}

	if extraPath != "" {
		extra, err := readExtraHooks(extraPath)
		if err != nil {
			fatal(err)
		}
		hooks = append(extra, hooks...)
	}

	if len(hooks) == 0 {
		fatal(errors.New("no hook targets discovered"))
	}

	if err := writeHeader(output, defPath, extraPath, hooks); err != nil {
		fatal(err)
	}
}

// fatal 打印错误并退出，简化错误处理分支。
func fatal(err error) {
	fmt.Fprintf(os.Stderr, "hookidgen: %v\n", err)
	os.Exit(1)
}

// readHookTargets 解析 .def 文件，提取符合格式的 Hook 名称。
func readHookTargets(defPath string) ([]string, error) {
	file, err := os.Open(defPath)
	if err != nil {
		return nil, fmt.Errorf("opening def file: %w", err)
	}
	defer file.Close()

	var hooks []string
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "//") {
			continue
		}
		matches := hookPattern.FindStringSubmatch(line)
		if len(matches) != 3 {
			continue
		}
		hooks = append(hooks, buildHookName(matches[2]))
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("reading def file: %w", err)
	}
	return hooks, nil
}

// readExtraHooks 读取额外 hook 列表，忽略注释和空行，并强制前缀。
func readExtraHooks(extraPath string) ([]string, error) {
	file, err := os.Open(extraPath)
	if err != nil {
		return nil, fmt.Errorf("opening extra hook file: %w", err)
	}
	defer file.Close()

	var hooks []string
	scanner := bufio.NewScanner(file)
	lineNumber := 0
	seen := make(map[string]struct{})
	for scanner.Scan() {
		lineNumber++
		raw := strings.TrimSpace(scanner.Text())
		if raw == "" || strings.HasPrefix(raw, "#") || strings.HasPrefix(raw, "//") {
			continue
		}
		if !strings.HasPrefix(raw, "uprobe_") {
			return nil, fmt.Errorf("extra hook %q (line %d) must start with 'uprobe_'", raw, lineNumber)
		}
		if _, ok := seen[raw]; ok {
			continue
		}
		hooks = append(hooks, raw)
		seen[raw] = struct{}{}
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("reading extra hook file: %w", err)
	}
	return hooks, nil
}

// buildHookName 确保 hook 名称带上 uprobe_ 前缀。
func buildHookName(target string) string {
	target = strings.TrimSpace(target)
	if strings.HasPrefix(target, "uprobe_") {
		return target
	}
	return "uprobe_" + target
}

// writeHeader 生成 hook_ids.h，记录每个 hook 对应的常量 ID。
func writeHeader(output, defPath, extraPath string, hooks []string) error {
	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		return fmt.Errorf("creating directory for %s: %w", output, err)
	}
	f, err := os.Create(output)
	if err != nil {
		return fmt.Errorf("creating header: %w", err)
	}
	defer f.Close()

	builder := &strings.Builder{}
	fmt.Fprintln(builder, "#pragma once")
	fmt.Fprintln(builder)
	fmt.Fprintln(builder, "// Code generated by hookidgen; DO NOT EDIT.")
	fmt.Fprintf(builder, "// Source: %s", filepath.Base(defPath))
	if extraPath != "" {
		fmt.Fprintf(builder, " + %s", filepath.Base(extraPath))
	}
	fmt.Fprintln(builder)

	if err := ensureUnique(hooks); err != nil {
		return err
	}
	for idx, name := range hooks {
		fmt.Fprintf(builder, "#define HOOK_%s %d\n", name, idx+1)
	}
	fmt.Fprintln(builder)
	fmt.Fprintf(builder, "#define HOOK_ID_COUNT %d\n", len(hooks))

	if _, err := f.WriteString(builder.String()); err != nil {
		return fmt.Errorf("writing header: %w", err)
	}
	return nil
}

// ensureUnique 确认 hook 名称不重复，避免生成冲突。
func ensureUnique(hooks []string) error {
	seen := make(map[string]int)
	for idx, name := range hooks {
		if prev, ok := seen[name]; ok {
			return fmt.Errorf("duplicate hook %s at positions %d and %d", name, prev, idx)
		}
		seen[name] = idx
	}
	return nil
}
